// Apply language to all elements with data-i18n and data-menu-i18n
function applyLanguage(lang) {
  if (!I18N[lang]) lang = "tr";
  const dict = I18N[lang];

  // Apply data-i18n translations
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key]) el.innerHTML = dict[key];
  });

  // Apply data-i18n-ph (placeholder) translations
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.dataset.i18nPh;
    if (dict[key]) el.placeholder = dict[key];
  });

  // Apply data-menu-i18n translations
  document.querySelectorAll("[data-menu-i18n]").forEach(el => {
    const key = el.dataset.menuI18n;
    if (dict[key]) el.innerHTML = dict[key];
  });

  // Update html lang and dir
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  // Update language button label
  const langBtn = document.querySelector(".language-button");
  if (langBtn) langBtn.firstChild.textContent = I18N_LANG_CODES[lang] + " ";

  // Update language menu items with native names
  document.querySelectorAll("[data-lang]").forEach(btn => {
    const l = btn.dataset.lang;
    if (I18N_LANG_NAMES[l]) btn.textContent = I18N_LANG_NAMES[l];
  });

  // Update document title
  if (lang === "de") document.title = "Eifeler Kebaphaus | Döner & Grill in Monschau";
  else if (lang === "en") document.title = "Eifeler Kebaphaus | Döner & Grill in Monschau";
  else document.title = "Eifeler Kebaphaus | Döner & Izgara in Monschau";

  // Update radio station description
  const radioDesc = document.getElementById("radio-station-desc");
  if (radioDesc && radioDesc.dataset.i18n && dict[radioDesc.dataset.i18n]) {
    radioDesc.textContent = dict[radioDesc.dataset.i18n];
  }

  // Save language preference
  try { localStorage.setItem("eifeler-lang", lang); } catch(e) {}
}

// Get saved language or default to browser language
function getSavedLanguage() {
  let lang = "tr";
  try { lang = localStorage.getItem("eifeler-lang") || "tr"; } catch(e) {}
  return I18N[lang] ? lang : "tr";
}

// Initialize language system
function initI18n() {
  const lang = getSavedLanguage();
  applyLanguage(lang);

  // Language menu toggle
  const langBtn = document.querySelector(".language-button");
  const langMenu = document.querySelector(".language-menu");
  if (langBtn && langMenu) {
    langBtn.addEventListener("click", () => {
      const open = langMenu.classList.toggle("open");
      langBtn.setAttribute("aria-expanded", open);
    });
    document.addEventListener("click", e => {
      if (!e.target.closest(".language-switcher")) {
        langMenu.classList.remove("open");
        langBtn.setAttribute("aria-expanded", "false");
      }
    });
  }

  // Language selection buttons
  document.querySelectorAll("[data-lang]").forEach(btn => {
    btn.addEventListener("click", () => {
      applyLanguage(btn.dataset.lang);
      langMenu.classList.remove("open");
      langBtn.setAttribute("aria-expanded", "false");
    });
  });
}

// Run on DOM ready
if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initI18n);
} else {
  initI18n();
}
